import os
import json
from pathlib import Path
from typing import Optional, Dict, Any

from app.models.schemas import (
    ApiTestingRequest,
    ApiTestingResponse,
    ApiFuzzTestCase,
)
from app.services.llm_service import LLMService


class ApiTester:
    """Agent generating automated REST API test suites, fuzz payloads, and security assertions."""

    def __init__(self, llm_service: Optional[LLMService] = None):
        self.llm_service = llm_service or LLMService()
        self.prompt_template = self._load_prompt_template()

    def _load_prompt_template(self) -> str:
        current_dir = Path(__file__).resolve().parent
        candidates = [
            current_dir.parent / "prompts" / "api_fuzz_prompt.txt",
            current_dir.parent.parent / "app" / "prompts" / "api_fuzz_prompt.txt",
            Path.cwd() / "backend" / "app" / "prompts" / "api_fuzz_prompt.txt",
        ]
        for c in candidates:
            if c.exists() and c.is_file():
                try:
                    with open(c, "r", encoding="utf-8") as f:
                        return f.read()
                except Exception:
                    pass
        return "Generate API tests for {method} {endpoint}:\n{request_body}"

    def _generate_fallback_api_tests(self, req: ApiTestingRequest) -> ApiTestingResponse:
        ep = req.endpoint or "/api/v1/resource"
        method = req.method.upper()

        test_cases = [
            ApiFuzzTestCase(
                id="API-01",
                name="Contract Schema Validation (Valid Payload)",
                category="contract",
                payload={"sample_key": "valid_value", "id": 101},
                expected_status=200 if method == "GET" else 201,
                expected_assertion="response.status_code in [200, 201] and response.json() is not None",
                description="Verifies standard happy path schema conformance and response structure."
            ),
            ApiFuzzTestCase(
                id="API-02",
                name="Negative Boundary: Empty & Missing Required Keys",
                category="negative",
                payload={},
                expected_status=400,
                expected_assertion="response.status_code in [400, 422]",
                description="Checks that omitting required parameters triggers appropriate client error."
            ),
            ApiFuzzTestCase(
                id="API-03",
                name="Security Fuzz: SQL Injection & Script Injection",
                category="security_fuzz",
                payload={"search": "' OR '1'='1' --", "comment": "<script>alert(1)</script>"},
                expected_status=400,
                expected_assertion="response.status_code in [400, 422] and '<script>' not in response.text",
                description="Confirms endpoint resists SQLi patterns and escapes HTML/XSS payloads."
            ),
            ApiFuzzTestCase(
                id="API-04",
                name="Auth Trap: Missing or Invalid Bearer Token",
                category="auth",
                payload={"sample_key": "valid_value"},
                expected_status=401,
                expected_assertion="response.status_code in [401, 403]",
                description="Ensures protected endpoints reject unauthorized or missing credentials."
            )
        ]

        py_script = (
            "# Automated REST API Test Suite generated by QA-Agent\n"
            "import requests\n"
            "import pytest\n\n"
            f"BASE_URL = 'http://localhost:8000'\n"
            f"ENDPOINT = '{ep}'\n\n"
            "def test_api_contract_valid():\n"
            f"    res = requests.{method.lower()}(f'{{BASE_URL}}{{ENDPOINT}}', json={{'key': 'value'}})\n"
            "    assert res.status_code in [200, 201]\n\n"
            "def test_api_negative_empty_payload():\n"
            f"    res = requests.{method.lower()}(f'{{BASE_URL}}{{ENDPOINT}}', json={{}})\n"
            "    assert res.status_code in [400, 422]\n"
        )

        curls = [
            f"curl -X {method} http://localhost:8000{ep} -H 'Content-Type: application/json' -d '{{\"test\": \"data\"}}'",
            f"curl -X {method} http://localhost:8000{ep} -H 'Content-Type: application/json' -d '{{}}'",
            f"curl -X {method} http://localhost:8000{ep} -H 'Content-Type: application/json' -d '{{\"id\": \"' OR 1=1 --\"}}'"
        ]

        return ApiTestingResponse(
            api_title=f"{method} {ep} Automated Test Suite",
            endpoint=ep,
            method=method,
            test_cases=test_cases,
            python_requests_script=py_script,
            curl_commands=curls
        )

    def generate_api_tests(self, req: ApiTestingRequest) -> ApiTestingResponse:
        prompt = self.prompt_template.replace("{endpoint}", req.endpoint.strip())
        prompt = prompt.replace("{method}", req.method.strip())
        prompt = prompt.replace("{headers}", json.dumps(req.headers or {}))
        prompt = prompt.replace("{request_body}", (req.request_body or "{}").strip())

        data = self.llm_service.generate_json(prompt, provider_override=req.provider)
        if not data or "test_cases" not in data:
            return self._generate_fallback_api_tests(req)

        try:
            return ApiTestingResponse(**data)
        except Exception:
            return self._generate_fallback_api_tests(req)

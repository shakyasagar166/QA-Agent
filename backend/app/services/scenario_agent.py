import os
from pathlib import Path
from typing import Optional, Dict, Any

from app.models.schemas import (
    ScenarioGenerationRequest,
    ScenarioGenerationResponse,
    GherkinScenario,
)
from app.services.llm_service import LLMService


class ScenarioAgent:
    """Agent synthesizing BDD Gherkin scenarios and Playwright/Cypress automated E2E test scripts."""

    def __init__(self, llm_service: Optional[LLMService] = None):
        self.llm_service = llm_service or LLMService()
        self.prompt_template = self._load_prompt_template()

    def _load_prompt_template(self) -> str:
        current_dir = Path(__file__).resolve().parent
        candidates = [
            current_dir.parent / "prompts" / "bdd_scenario_prompt.txt",
            current_dir.parent.parent / "app" / "prompts" / "bdd_scenario_prompt.txt",
            Path.cwd() / "backend" / "app" / "prompts" / "bdd_scenario_prompt.txt",
        ]
        for c in candidates:
            if c.exists() and c.is_file():
                try:
                    with open(c, "r", encoding="utf-8") as f:
                        return f.read()
                except Exception:
                    pass
        return "Generate BDD scenarios for {framework}:\n{user_story}"

    def _generate_fallback_scenarios(self, req: ScenarioGenerationRequest) -> ScenarioGenerationResponse:
        fw = req.framework or "Playwright"

        scenarios = [
            GherkinScenario(
                scenario_name="Successful Happy Path User Journey",
                scenario_type="Positive",
                steps=[
                    "Given the user is on the target application page",
                    "When the user inputs valid required data into the form",
                    "And clicks the primary confirmation submit button",
                    "Then the application displays a success notification with expected response data",
                    "And updates the database or state accordingly"
                ]
            ),
            GherkinScenario(
                scenario_name="Missing Required Fields Boundary Trap",
                scenario_type="Negative",
                steps=[
                    "Given the user is on the target form",
                    "When the user leaves mandatory input fields empty",
                    "And attempts to trigger form submission",
                    "Then an inline error validation message is clearly displayed",
                    "And the submit action is prevented from executing"
                ]
            ),
            GherkinScenario(
                scenario_name="Network Latency & Offline Recovery Check",
                scenario_type="Boundary",
                steps=[
                    "Given the user initiates an action under simulated degraded network conditions",
                    "When the server takes longer than normal to respond",
                    "Then an accessible loading spinner is rendered",
                    "And retry mechanisms prevent duplicate state mutations"
                ]
            )
        ]

        if fw.lower() == "cypress":
            test_code = (
                "// Cypress Automated Test Suite generated by QA-Agent\n"
                "describe('Feature End-to-End Suite', () => {\n"
                "  beforeEach(() => {\n"
                "    cy.visit('/');\n"
                "  });\n\n"
                "  it('completes primary positive workflow successfully', () => {\n"
                "    cy.get('[data-testid=\"input-field\"]').type('Sample Input');\n"
                "    cy.get('[data-testid=\"submit-btn\"]').click();\n"
                "    cy.get('[data-testid=\"success-banner\"]').should('be.visible');\n"
                "  });\n\n"
                "  it('displays validation message on empty submission', () => {\n"
                "    cy.get('[data-testid=\"submit-btn\"]').click();\n"
                "    cy.get('.error-message').should('contain', 'Required');\n"
                "  });\n"
                "});\n"
            )
            instructions = "npx cypress run"
        else:
            test_code = (
                "// Playwright Automated E2E Test Suite generated by QA-Agent\n"
                "import { test, expect } from '@playwright/test';\n\n"
                "test.describe('Feature E2E Acceptance Suite', () => {\n"
                "  test.beforeEach(async ({ page }) => {\n"
                "    await page.goto('/');\n"
                "  });\n\n"
                "  test('should execute happy path journey successfully', async ({ page }) => {\n"
                "    await page.locator('[data-testid=\"input-field\"]').fill('Valid Test Data');\n"
                "    await page.locator('[data-testid=\"submit-btn\"]').click();\n"
                "    await expect(page.locator('[data-testid=\"success-banner\"]')).toBeVisible({ timeout: 5000 });\n"
                "  });\n\n"
                "  test('should enforce input validation when required fields are omitted', async ({ page }) => {\n"
                "    await page.locator('[data-testid=\"submit-btn\"]').click();\n"
                "    await expect(page.locator('.validation-error')).toBeVisible();\n"
                "  });\n"
                "});\n"
            )
            instructions = "npx playwright test"

        return ScenarioGenerationResponse(
            feature_title="Automated BDD Feature Acceptance Specification",
            summary=f"Synthesized 3 Gherkin scenarios (Positive, Negative, and Boundary) with automated {fw} test script.",
            target_framework=fw,
            gherkin_scenarios=scenarios,
            executable_test_code=test_code,
            setup_instructions=instructions
        )

    def generate_scenarios(self, req: ScenarioGenerationRequest) -> ScenarioGenerationResponse:
        prompt = self.prompt_template.replace("{user_story}", req.user_story.strip())
        prompt = prompt.replace("{framework}", (req.framework or "Playwright").strip())

        data = self.llm_service.generate_json(prompt, provider_override=req.provider)
        if not data or "gherkin_scenarios" not in data:
            return self._generate_fallback_scenarios(req)

        try:
            return ScenarioGenerationResponse(**data)
        except Exception:
            return self._generate_fallback_scenarios(req)
